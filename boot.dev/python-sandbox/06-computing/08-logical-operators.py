# * Logical operators: and / or
# * They combine True / False. Capital T/F in Python (JS: true / false).
# * and  → both must be True
# * or   → at least one True
# ?
# ? True  and True   →  True
# ? True  and False  →  False
# ? False and False  →  False
# ?
# ? True  or True    →  True
# ? True  or False   →  True
# ? False or False   →  False
# ?
# ? JS: && is and,  || is or
# ?     true && false  →  false
# ?     true || false  →  true
# ?
# ? Ops flavour: "deploy if tests passed *and* image exists"
# ?              "page if health is down *or* disk is full"

# * Parentheses: evaluate the inner () first, like JS.
# ? (True or False) and False
# ? True            and False  →  False

# * Q: ((True and True) or (True and False)) ?
# * A: True
# ?    True or False  →  True
