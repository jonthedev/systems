# * Variable Names
# * Names must not have spaces. They are one continuous token.
# * Guido van Rossum (Python's creator) asks us to use snake_case.

# ? | Style       | Example        | Typical in            |
# ? | ----------- | -------------- | --------------------- |
# ? | Snake Case  | num_new_users  | Python, Ruby, Rust    |
# ? | Camel Case  | numNewUsers    | JavaScript, Java      |
# ? | Pascal Case | NumNewUsers    | C#, C++               |
# ? | No casing   | numnewusers    | just don't            |

# * Camel Case and Pascal Case still run in Python. The point is
# * consistency. You already write camelCase in JS, here we switch
# * to snake_case.

 